#!/usr/bin/env node
// Writes src/styles/vendor/bootstrap.css: Bootstrap's stylesheet without the rules
// for classes this site never uses.
//
// The site takes only Bootstrap's CSS — grid, a handful of utilities, modal,
// navbar and form controls — about a tenth of the 230 KB file. Shipping all of
// it made Bootstrap the largest render-blocking request on mobile.
//
// A rule is dropped only when every class in its selector is absent from the
// source: any word in src/ counts as "used", so the check errs on the side of
// keeping. Rule order and content are untouched, so the cascade is identical.
//
// Runs automatically before `npm run dev` and `npm run build` (see
// package.json), so a Bootstrap class added to a component is included the
// next time either starts. Do not edit the generated file by hand.
//
// Usage: node scripts/purge-bootstrap.mjs

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import postcss from "postcss";

const SOURCE = "node_modules/bootstrap/dist/css/bootstrap.min.css";
const OUTPUT = "src/styles/vendor/bootstrap.css";

// Classes toggled at runtime by code outside src/ (none today, but keep the
// state classes Bootstrap styles in case a library starts adding them).
const ALWAYS_KEEP = new Set(["show", "active", "disabled", "collapsed"]);

function sourceFiles(dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) sourceFiles(path, out);
    else if (/\.(tsx?|jsx?|mjs)$/.test(entry.name)) out.push(path);
  }
  return out;
}

const usedWords = new Set(ALWAYS_KEEP);
for (const file of sourceFiles("src")) {
  for (const [word] of readFileSync(file, "utf8").matchAll(/[A-Za-z_][\w-]*/g)) {
    usedWords.add(word);
  }
}

const classNames = (selector) =>
  [...selector.replace(/\\./g, "").matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)].map((m) => m[1]);

const root = postcss.parse(readFileSync(SOURCE, "utf8"), { from: SOURCE });
const before = root.toString().length;

root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  const kept = rule.selectors.filter((selector) =>
    classNames(selector).every((name) => usedWords.has(name)),
  );
  if (kept.length === 0) rule.remove();
  else if (kept.length !== rule.selectors.length) rule.selectors = kept;
});

// Remove @media / @supports blocks left empty.
let removedBlock = true;
while (removedBlock) {
  removedBlock = false;
  root.walkAtRules((atRule) => {
    if (atRule.nodes && atRule.nodes.length === 0) {
      atRule.remove();
      removedBlock = true;
    }
  });
}

root.walkComments((comment) => {
  if (comment.text.startsWith("# sourceMappingURL")) comment.remove();
});

const header =
  "/* Generated by scripts/purge-bootstrap.mjs from bootstrap.min.css - do not edit. */\n";
const css = header + root.toString();
writeFileSync(OUTPUT, css);

console.log(
  `purge-bootstrap: ${(before / 1024).toFixed(0)} KB -> ${(css.length / 1024).toFixed(0)} KB (${OUTPUT})`,
);
